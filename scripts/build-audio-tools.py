#!/usr/bin/env python3
"""Build only from the declared registry lock and checksum-pinned runtime."""
import hashlib,json,os,shutil,subprocess,sys,tarfile,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
APP=ROOT/'audio_tools'
MODULES=['dsp','noise','safety','clip','edit','pcm','clip_pcm','recipe','levels','block','automation','delay']
RUNTIME_SHA='e375ec1127ecc0d5d4f3b2f0775aa321d35dcc3a07f5a9a19f7857b618b160b0'
CONTENT='sha256:67c03510f1402ff908b8a84c872e8bc6b508e6f5cbbab55f06382bcd613655f5'
def main():
    if len(sys.argv)!=2: raise SystemExit('Usage: scripts/build-audio-tools.sh OUTPUT_DIRECTORY')
    dest=Path(sys.argv[1]).resolve()
    if dest in [ROOT,APP,ROOT/'site',ROOT/'site/audio-tools']:raise SystemExit('Refusing source directory destination')
    if dest.exists() and any(dest.iterdir()):
        if not (dest/'.audio-tools-generated').is_file():raise SystemExit('Destination must be empty or an existing generated audio artifact')
        shutil.rmtree(dest)
    subprocess.run(['ailang','lock','--check'],cwd=APP,check=True)
    lock=json.loads((APP/'ailang.lock').read_text())
    assert len(lock['packages'])==1
    pkg=lock['packages'][0]
    assert (pkg['name'],pkg['version'],pkg['source'],pkg['content_hash'])==('sunholo/audio','0.4.0','registry',CONTENT)
    cache=Path(os.environ.get('AILANG_CACHE',str(Path.home()/'.ailang/cache/registry')))/pkg['name']/pkg['version']
    assert cache.is_dir(), 'Run cd audio_tools && ailang lock to populate the registry cache'
    version=(APP/'.ailang-version').read_text().strip()
    assert version=='v0.54.18', 'Runtime checksum must be reviewed with a version change'
    shutil.copytree(ROOT/'site/audio-tools',dest)
    (dest/'.audio-tools-generated').write_text('Generated by scripts/build-audio-tools.py\n')
    (dest/'wasm').mkdir()
    with tempfile.TemporaryDirectory(prefix='audio-runtime-') as scratch:
        archive=Path(scratch)/'runtime.tar.gz'
        subprocess.run(['curl','-fLsS','--retry','3','--max-time','120',f'https://github.com/sunholo-data/ailang/releases/download/{version}/ailang-wasm.tar.gz','-o',str(archive)],check=True)
        assert hashlib.sha256(archive.read_bytes()).hexdigest()==RUNTIME_SHA, 'Runtime archive checksum mismatch'
        with tarfile.open(archive) as tar:
            for name in ['ailang.wasm','wasm_exec.js']:
                entry=tar.extractfile(name)
                assert entry is not None
                (dest/'wasm'/name).write_bytes(entry.read())
    modules=[]
    for name in MODULES:
        target=dest/'ailang/pkg/sunholo/audio'/f'{name}.ail';target.parent.mkdir(parents=True,exist_ok=True)
        shutil.copyfile(cache/f'{name}.ail',target)
        modules.append({'name':f'pkg/sunholo/audio/{name}','path':target.relative_to(dest).as_posix(),'sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
    target=dest/'host.ail';shutil.copyfile(APP/'host.ail',target)
    modules.append({'name':'host','path':'host.ail','sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
    (dest/'modules.json').write_text(json.dumps(modules,indent=2)+'\n')
    shutil.copyfile(APP/'AUDIO-LICENSE',dest/'AUDIO-LICENSE')
    metadata={'runtime':version,'runtimeArchiveSha256':RUNTIME_SHA,'wasmSha256':hashlib.sha256((dest/'wasm/ailang.wasm').read_bytes()).hexdigest(),'package':'sunholo/audio@0.4.0','contentHash':CONTENT,'interfaceHash':pkg['interface_hash']}
    (dest/'build.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(f'Built audio tools at {dest}')
if __name__=='__main__':main()
